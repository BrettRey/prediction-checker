#!/usr/bin/env python3
"""Case 2 input checks (rules in notes/analysis-plan.md): unbundled uptake,
closures, and two post hoc mechanism series (payments to Canadian services and
their share). Numbers are read from source files, not typed.

Inputs
  literature/crtc_2016-04-15_66000_basic_tv_package_release.md
  literature/crtc_2016-09-07_hearing_transcript_bdu_renewals.md
  data/derived/crtc_lttv_outcomes.csv     (BDU subscribers)
  data/derived/closures_summary.csv       (scripts/closures_lttv.py)
  data/raw/crtc/cmr_bdu_sector_2013-2024.xlsx  (CMR Table U-T11)
Outputs
  data/derived/uptake_crtc.csv
  notes/results-lttv-inputs.md  (generated; do not edit by hand)
"""
import csv
import re
import warnings
from pathlib import Path

import openpyxl

warnings.filterwarnings("ignore")
ROOT = Path(__file__).resolve().parents[1]
LIT = ROOT.parents[2] / "literature"
DER = ROOT / "data" / "derived"
RAW = ROOT / "data" / "raw" / "crtc"


def find(path, pattern):
    m = re.search(pattern, path.read_text())
    if not m:
        raise SystemExit(f"{path.name}: pattern not found: {pattern}")
    return int(m.group(1).replace(",", ""))


apr = find(LIT / "crtc_2016-04-15_66000_basic_tv_package_release.md",
           r"In just five weeks, more than ([\d,]+) Canadians have already signed up")
jun = find(LIT / "crtc_2016-09-07_hearing_transcript_bdu_renewals.md",
           r"As of June 30\S*, 2016, ([\d,]+) Canadians had signed up for the affordable basic service")
subs = {int(r["year"]): float(r["value"]) for r in csv.DictReader(open(DER / "crtc_lttv_outcomes.csv"))
        if r["series"] == "bdu_subscribers_thousands"}
den = subs[2016] * 1000
uptake = [("early April 2016 (five weeks after launch)", apr, "CRTC news release, 15 April 2016"),
          ("30 June 2016", jun, "CRTC Chairman, hearing of 7 September 2016, para. 12")]
with open(DER / "uptake_crtc.csv", "w", newline="") as f:
    w = csv.writer(f)
    w.writerow(["as_of", "entry_level_subscribers", "bdu_subscribers_2016", "share", "source"])
    for when, n, src in uptake:
        w.writerow([when, n, int(den), round(n / den, 4), src])

closures = list(csv.DictReader(open(DER / "closures_summary.csv")))

wb = openpyxl.load_workbook(RAW / "cmr_bdu_sector_2013-2024.xlsx", read_only=True, data_only=True)
t11, hdr = {}, None
for r in wb["U-T11"].iter_rows(values_only=True):
    if r and r[0] == "Category":
        hdr = {i: int(c) for i, c in enumerate(r) if c is not None and str(c).isdigit()}
        continue
    if hdr and r and ((r[0] == "Canadian affiliates" and r[1] == "Total") or r[0] == "All affiliates"):
        t11[r[0]] = {y: float(r[i]) for i, y in hdr.items() if r[i] not in (None, "")}
can, allp = t11["Canadian affiliates"], t11["All affiliates"]

L = ["# Results: case 2 input checks",
     "<!-- SUMMARY: Generated by scripts/input_checks_lttv.py; uptake, closures, and post hoc mechanism series for the "
     "Let's Talk TV forecast · status: generated · updated: 2026-10-03 -->",
     "",
     "Generated by `scripts/input_checks_lttv.py`; do not edit by hand. Rules: `notes/analysis-plan.md`. "
     "[post hoc] marks choices made after the data were seen.",
     "",
     "## Unbundled uptake",
     "",
     "Report: BYOP (entry-level plus picks) 5% of BDU subscribers in 2016, 10% in 2017, 15% in 2018-2020 (Table 18); "
     "cited studies 10-35% (para. 201). Morrison to the Heritage Committee, April 2016: 'about 4% of Canadians will go for it'.",
     "",
     "| As of | Entry-level subscribers | Share of 2016 BDU subscribers | Source |",
     "|---|---|---|---|"]
for when, n, src in uptake:
    L.append(f"| {when} | {n:,} | {n / den:.1%} | {src} |")
L += ["",
      "CRTC-published counts (the plan's first tier) exist only for 2016, months after launch, so they can't settle the "
      "report's 2017-2018 values. Company disclosures (second tier) not yet searched. The April release adds that "
      "'more than 1 out of 3' of the 66,000 also took individual channels or small packages.",
      "",
      "## Closures, 2015 to 2019-2020",
      "",
      "Report: by 2020, 10% of vertically integrated Category A/B services and 25% of independent A/B services shut "
      "(paras. 232-233); Bell suggested about 25% of its services, Oliver Wyman 26% (para. 230). Bounds [post hoc]: the "
      "lower counts services still listed with no revenue in 2019 and 2020; the upper adds services no longer listed, "
      "which closed or became exempt (exempt services file but aren't published individually). Crosswalk: "
      "`data/derived/closures_crosswalk.csv`.",
      "",
      "| Corus counted as VI | Group | Services in 2015 | Operating | Closed | Not listed | Share closed (bounds) |",
      "|---|---|---|---|---|---|---|"]
for c in closures:
    L.append(f"| {c['corus_counted_vi']} | {c['group']} | {c['n_2015']} | {c['operating']} | {c['closed']} | "
             f"{c['absent']} | {float(c['share_closed_lower']):.0%}-{float(c['share_closed_upper']):.0%} |")
L += ["",
      "Vertically integrated: the bounds sit around the report's 10% and below the 25-26% it cites from Bell and Oliver "
      "Wyman. Independent: too wide to compare with 25%.",
      "",
      "## Payments to Canadian services [post hoc observables]",
      "",
      "CRTC CMR Table U-T11, affiliation payments by BDUs ($M). The report's pass-through (para. 207) implies falling "
      "payments to Canadian services; its preponderance change (para. 212) implies the Canadian share falling among BYOP "
      "subscribers from 86% to 50% by 2020, roughly 81% overall at 15% BYOP uptake.",
      "",
      "| Year | " + " | ".join(str(y) for y in range(2013, 2021)) + " |",
      "|---|" + "---|" * 8,
      "| To Canadian services | " + " | ".join(f"{can[y]:,.0f}" for y in range(2013, 2021)) + " |",
      "| To all services | " + " | ".join(f"{allp[y]:,.0f}" for y in range(2013, 2021)) + " |",
      "| Canadian share | " + " | ".join(f"{can[y] / allp[y]:.1%}" for y in range(2013, 2021)) + " |",
      ""]
(ROOT / "notes" / "results-lttv-inputs.md").write_text("\n".join(L) + "\n")
print(f"uptake: April {apr:,} ({apr / den:.1%}), June {jun:,} ({jun / den:.1%}); "
      f"Canadian share 2015 {can[2015] / allp[2015]:.1%}, 2019 {can[2019] / allp[2019]:.1%}")
