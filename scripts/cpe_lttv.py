#!/usr/bin/env python3
"""Case 2, Canadian programming expenditure (descriptive only; reading rule 4
in notes/analysis-plan.md: no conclusion about the forecast rests on CPE).

Report's definition (Figs. 8, 9, 43): programming services' CPE including
CBC/SRC conventional, plus BDU contributions to the CMF, independent funds and
community channels (local expression); LPIF excluded (para. 187).

CRTC sources (data/raw/crtc/, Open Government Licence - Canada):
  discretionary and on-demand: 'Total Canadian Programming' (sheet 1), less
    exempt services from 2016 (sheet 10, 2020 vintage) [post hoc, as for revenue]
  private conventional: 'Canadian Programming Expenses (CPE)' (sheet 1)
  CBC/SRC conventional: 'Canadian Programming Expenses (CPE)' (sheet 13)
  BDU contributions: CMR Table U-T10, CMF + local expression + other
    independent funds (ILNF, from 2019, shown separately)
2012-2015 from the 2016 vintage, 2016-2020 from the 2020 vintage.

Outputs: data/derived/cpe_lttv.csv, notes/results-lttv-cpe.md (generated)
"""
import csv
import sys
import warnings
from pathlib import Path

import openpyxl

sys.path.insert(0, str(Path(__file__).resolve().parent))
from crtc_outcomes_lttv import sheet_series  # noqa: E402

warnings.filterwarnings("ignore")
ROOT = Path(__file__).resolve().parents[1]
RAW = ROOT / "data" / "raw" / "crtc"
DER = ROOT / "data" / "derived"
YEARS = range(2012, 2021)


def two_vintages(f16, f20, sheet, label, scale=1e6):
    a = sheet_series(RAW / f16, sheet, label)
    b = sheet_series(RAW / f20, sheet, label)
    return {y: (b[y] if y >= 2016 else a[y]) / scale for y in YEARS if (y >= 2016 and y in b) or (y < 2016 and y in a)}


dod = two_vintages("sfs2016_discretionary_ondemand.xlsx", "sfs2020_discretionary_ondemand.xlsx", "1", "Total Canadian Programming")
exempt = {y: v / 1e6 for y, v in sheet_series(RAW / "sfs2020_discretionary_ondemand.xlsx", "10", "Total Canadian Programming").items()}
dod_ex = {y: v - exempt.get(y, 0.0) for y, v in dod.items()}
priv = two_vintages("sfs2016_conventional.xlsx", "sfs2020_conventional.xlsx", "1", "Canadian Programming Expenses (CPE)")
cbc = two_vintages("sfs2016_conventional.xlsx", "sfs2020_conventional.xlsx", "13", "Canadian Programming Expenses (CPE)")

ws = openpyxl.load_workbook(RAW / "cmr_bdu_sector_2013-2024.xlsx", read_only=True, data_only=True)["U-T10"]
rows = [list(r) for r in ws.iter_rows(values_only=True)]
hdr = next(r for r in rows if any(c == 2012 for c in r))
col = {c: i for i, c in enumerate(hdr) if isinstance(c, int)}
bdu_parts = {}
for r in rows:
    lab = str(r[0]).strip() if r[0] else ""
    if lab in ("Contribution to the CMF", "Local Expression", "Contributions to other independent funds",
               "Independent Local News Fund (ILNF)"):
        bdu_parts[lab] = {y: (float(r[col[y]]) if isinstance(r[col[y]], (int, float)) else 0.0) for y in YEARS}
bdu = {y: sum(bdu_parts[k][y] for k in ("Contribution to the CMF", "Local Expression",
                                        "Contributions to other independent funds")) for y in YEARS}
ilnf = bdu_parts["Independent Local News Fund (ILNF)"]

fc = {(r["quantity"], int(r["year"])): r for r in csv.DictReader(open(DER / "nordicity_2015_scenarios.csv"))}
total = {y: dod_ex[y] + priv[y] + cbc[y] + bdu[y] for y in YEARS}

with open(DER / "cpe_lttv.csv", "w", newline="") as f:
    w = csv.writer(f)
    w.writerow(["year", "discretionary_ondemand_excl_exempt", "private_conventional", "cbc_conventional",
                "bdu_contributions", "ilnf", "total", "report_baseline", "report_lttv"])
    for y in YEARS:
        r = fc.get(("cpe", y))
        w.writerow([y, round(dod_ex[y], 1), round(priv[y], 1), round(cbc[y], 1), round(bdu[y], 1), round(ilnf[y], 1),
                    round(total[y], 1), r["baseline_level"] if r else "", r["lttv_level"] if r else ""])

L = ["# Results: case 2, Canadian programming expenditure (descriptive)",
     "<!-- SUMMARY: Generated by scripts/cpe_lttv.py; CPE against the report's paths, descriptive only under reading rule 4 · status: generated · updated: 2026-10-03 -->",
     "", "Generated by `scripts/cpe_lttv.py`; do not edit by hand. Descriptive only: the design analysis found CPE too volatile "
     "(9% a year, 2010-2014) to test the forecast, so no conclusion rests on this table.", "",
     "## Splice check against the report's 2012-2014 values", "",
     "| Year | Report | CRTC (same definition) | Difference |", "|---|---|---|---|"]
for y in (2012, 2013, 2014):
    rep = float(fc[("cpe", y)]["baseline_level"])
    L.append(f"| {y} | {rep:,.0f} | {total[y]:,.0f} | {total[y] / rep - 1:+.1%} |")
L += ["", "## CPE against the report's paths ($M)", "",
      "| Year | Discretionary and on-demand | Private conventional | CBC/SRC conventional | BDU contributions | Total | Report baseline | Report LTTV |",
      "|---|---|---|---|---|---|---|---|"]
for y in YEARS:
    r = fc.get(("cpe", y))
    b = f"{float(r['baseline_level']):,.0f}" if r and y >= 2016 else ""
    l_ = f"{float(r['lttv_level']):,.0f}" if r and y >= 2016 else ""
    L.append(f"| {y} | {dod_ex[y]:,.0f} | {priv[y]:,.0f} | {cbc[y]:,.0f} | {bdu[y]:,.0f} | {total[y]:,.0f} | {b} | {l_} |")
L += ["", "BDU contributions exclude the LPIF (as the report does) and the Independent Local News Fund, which began in 2019 "
      f"({ilnf[2019]:.0f} in 2019, {ilnf[2020]:.0f} in 2020; CMR Table U-T10).", ""]
(ROOT / "notes" / "results-lttv-cpe.md").write_text("\n".join(L) + "\n")
print("\n".join(L[6:12]))
print({y: round(total[y]) for y in YEARS})
