#!/usr/bin/env python3
"""Case 2, direct employment (reading rule 6 in notes/analysis-plan.md: tested
if a series with a pre-2015 level is found; the CRTC summaries carry staff
counts, so it is).

Observables (CRTC Statistical and Financial Summaries; 2016 vintage for
2012-2015, 2020 vintage for 2016-2020):
  channels: discretionary and on-demand 'Total Staff Count' (sheet 1), less
    exempt services from 2016 (sheet 10), matching the revenue series
  distributors: BDU basic and non-basic 'Total Staff Count (FTE)' (2016
    vintage) / 'Total Staff Count' (2020 vintage), sheet 1
Forecast: Table 22 direct FTE impacts by sector and year (relative to the
report's baseline, whose employment path the report doesn't give).

This isn't a k estimate: with no baseline employment path, the comparison is
the observed change from 2015 against (a) the forecast direct impact and (b)
a crude no-reform path, the 2012-2015 linear trend extended to 2019.

Outputs: data/derived/employment_lttv.csv, notes/results-lttv-employment.md
"""
import csv
import sys
from pathlib import Path

import numpy as np

sys.path.insert(0, str(Path(__file__).resolve().parent))
from crtc_outcomes_lttv import sheet_series  # noqa: E402

ROOT = Path(__file__).resolve().parents[1]
RAW = ROOT / "data" / "raw" / "crtc"
DER = ROOT / "data" / "derived"
YEARS = range(2012, 2021)

ch16 = sheet_series(RAW / "sfs2016_discretionary_ondemand.xlsx", "1", "Total Staff Count")
ch20 = sheet_series(RAW / "sfs2020_discretionary_ondemand.xlsx", "1", "Total Staff Count")
ex20 = sheet_series(RAW / "sfs2020_discretionary_ondemand.xlsx", "10", "Total Staff Count")
bd16 = sheet_series(RAW / "sfs2016_distribution.xlsx", "1", "Total Staff Count (FTE)")
bd20 = sheet_series(RAW / "sfs2020_distribution.xlsx", "1", "Total Staff Count")
channels = {y: (ch20[y] - ex20.get(y, 0.0)) if y >= 2016 else ch16[y] for y in YEARS}
distrib = {y: bd20[y] if y >= 2016 else bd16[y] for y in YEARS}
vintage_gap = {"channels_2016": ch20[2016] - ch16[2016], "distributors_2016": bd20[2016] - bd16[2016]}

tf = {(r["fact"], int(r["year"])): float(r["value"]) for r in csv.DictReader(open(DER / "nordicity_2015_text_facts.csv"))}
fc = {"channels": {y: tf[("sector_fte_specialty_and_pay_tv_services_direct", y)] for y in range(2015, 2021)},
      "distributors": {y: tf[("sector_fte_bdus_direct", y)] for y in range(2015, 2021)}}

rows, summary = [], {}
for name, series in (("channels", channels), ("distributors", distrib)):
    pre = np.array([series[y] for y in range(2012, 2016)])
    slope, icept = np.polyfit(np.arange(2012, 2016), pre, 1)
    trend = {y: slope * y + icept for y in YEARS}
    for y in YEARS:
        rows.append(dict(sector=name, year=y, staff=round(series[y]), pre2015_trend=round(trend[y]),
                         forecast_direct_impact=-fc[name].get(y, 0.0) if y >= 2015 else ""))
    change = series[2019] - series[2015]
    vs_trend = series[2019] - trend[2019]
    summary[name] = dict(staff2015=series[2015], staff2019=series[2019], change=change,
                         trend2019=trend[2019], vs_trend=vs_trend, forecast2019=-fc[name][2019],
                         slope=slope)

with open(DER / "employment_lttv.csv", "w", newline="") as f:
    w = csv.DictWriter(f, fieldnames=list(rows[0]))
    w.writeheader()
    w.writerows(rows)
with open(DER / "employment_lttv_summary.csv", "w", newline="") as f:
    w = csv.writer(f)
    w.writerow(["sector", "key", "value"])
    for name, d in summary.items():
        for k, v in d.items():
            w.writerow([name, k, round(v, 1)])
    for k, v in vintage_gap.items():
        w.writerow(["vintage", k, round(v, 1)])

L = ["# Results: case 2, direct employment",
     "<!-- SUMMARY: Generated by scripts/employment_lttv.py; CRTC staff counts for channels and distributors against the report's direct FTE impacts (rule 6) · status: generated · updated: 2026-10-03 -->",
     "", "Generated by `scripts/employment_lttv.py`; do not edit by hand. Reading rule 6 of `notes/analysis-plan.md`. "
     "Staff counts are CRTC-reported headcounts or FTEs, not the report's modelled FTEs; the report gives impacts relative "
     "to a baseline whose employment path it doesn't publish, so this is a level-change comparison, not a *k* estimate.", "",
     "| Sector | Staff 2015 | Staff 2019 | Change | 2012-2015 trend to 2019 | Observed vs trend | Report's direct impact by 2019 |",
     "|---|---|---|---|---|---|---|"]
for name, d in summary.items():
    L.append(f"| {name} | {d['staff2015']:,.0f} | {d['staff2019']:,.0f} | {d['change']:+,.0f} | {d['trend2019']:,.0f} | "
             f"{d['vs_trend']:+,.0f} | {d['forecast2019']:+,.0f} |")
L += ["", "Caveats: channels exclude exempt services from 2016, as the revenue series does; the distributor series changes "
      f"label from FTE (2016 vintage) to staff count (2020 vintage), and the two vintages differ by {vintage_gap['distributors_2016']:+,.0f} "
      f"in 2016 (channels: {vintage_gap['channels_2016']:+,.0f}). A linear 2012-2015 trend is a crude stand-in for the report's "
      "unpublished baseline employment path.", "",
      "| Year | " + " | ".join(str(y) for y in YEARS) + " |", "|---|" + "---|" * len(YEARS),
      "| Channels staff | " + " | ".join(f"{channels[y]:,.0f}" for y in YEARS) + " |",
      "| Distributors staff | " + " | ".join(f"{distrib[y]:,.0f}" for y in YEARS) + " |", ""]
(ROOT / "notes" / "results-lttv-employment.md").write_text("\n".join(L) + "\n")
print("\n".join(L[5:9]))
